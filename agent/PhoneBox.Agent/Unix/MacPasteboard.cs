using System.Runtime.InteropServices;

namespace PhoneBox.Agent;

/// <summary>
/// NSPasteboard calls run inside a native exception boundary. Each poll or write also has
/// its own autorelease pool because the agent's timer and request threads do not provide one.
/// </summary>
internal sealed class MacPasteboard : ITextPasteboard
{
    private const string ObjC = "/usr/lib/libobjc.A.dylib";
    private const string AppKit = "/System/Library/Frameworks/AppKit.framework/AppKit";
    private const string PlainText = "public.utf8-plain-text";

    /// <summary>
    /// Types that password managers and other programs add to what they copy to say "do not keep or pass this on"; an item
    /// carrying any of them is never shared. Only the presence of the type is checked: its data is never read (KeePassXC puts
    /// the secret itself in the concealed type).
    /// </summary>
    private static readonly string[] Withheld =
    [
        // The nspasteboard.org markers (http://nspasteboard.org/), which clipboard managers honour (Maccy's Clipboard.swift,
        // Clipy, Alfred). Concealed is what Bitwarden desktop writes (arboard's exclude_from_history, an empty string for the
        // type, after the text), and KeePassXC (src/gui/Clipboard.cpp), Strongbox (macbox ClipboardManager.m), Chrome
        // (ui/base/clipboard/clipboard_constants_mac.mm, for password copies) and Firefox 118+ (bug 1801880) write it too.
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        // Older markers the nspasteboard.org page asks programs to honour as well, and Maccy ignores by default
        // (Maccy/Extensions/Defaults.Keys+Names.swift): 1Password's own type, TextExpander and Butler, TypeIt4Me, Typinator.
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ];

    [DllImport(ObjC)] private static extern nint objc_getClass(string name);
    [DllImport(ObjC)] private static extern nint sel_registerName(string name);
    [DllImport(ObjC)] private static extern nint objc_autoreleasePoolPush();
    [DllImport(ObjC)] private static extern void objc_autoreleasePoolPop(nint pool);
    private const string Native = "PhoneBoxPasteboard";
    private enum Call { Pointer, PointerWithArgument, PointerWithThreeArguments, Integer, Size, BooleanOne, BooleanTwo }

    [DllImport(Native, EntryPoint = "phonebox_pasteboard_invoke")]
    private static extern int InvokeNative(nint receiver, nint selector, nuint a, nuint b, nuint c, Call call, out nuint value);

    private static nuint Invoke(nint receiver, nint selector, Call call, nuint a = 0, nuint b = 0, nuint c = 0)
    {
        if (InvokeNative(receiver, selector, a, b, c, call, out var value) == 0)
            throw new InvalidOperationException("The macOS pasteboard did not complete the operation.");
        return value;
    }

    private static nint Send(nint receiver, nint selector) => (nint)Invoke(receiver, selector, Call.Pointer);
    private static nint Send(nint receiver, nint selector, nint a) => (nint)Invoke(receiver, selector, Call.PointerWithArgument, (nuint)a);
    private static nint SendAt(nint receiver, nint selector, nuint index) => (nint)Invoke(receiver, selector, Call.PointerWithArgument, index);
    private static nint SendBytes(nint receiver, nint selector, nint bytes, nuint length, nuint encoding) =>
        (nint)Invoke(receiver, selector, Call.PointerWithThreeArguments, (nuint)bytes, length, encoding);
    private static nuint SendLength(nint receiver, nint selector, nuint encoding) => Invoke(receiver, selector, Call.Size, encoding);
    private static long SendLong(nint receiver, nint selector) => (long)Invoke(receiver, selector, Call.Integer);
    private static bool SendBool(nint receiver, nint selector, nint a) => Invoke(receiver, selector, Call.BooleanOne, (nuint)a) != 0;
    private static bool SendBool(nint receiver, nint selector, nint a, nint b) => Invoke(receiver, selector, Call.BooleanTwo, (nuint)a, (nuint)b) != 0;

    internal static void ReadOutsideNativeArrayForTest()
    {
        if (!Loaded.Value) throw new PlatformNotSupportedException("Foundation is unavailable.");
        var pool = objc_autoreleasePoolPush();
        try { SendAt(Send(objc_getClass("NSArray"), Sel("array")), Sel("objectAtIndex:"), 0); }
        finally { objc_autoreleasePoolPop(pool); }
    }

    private static readonly Lazy<bool> Loaded = new(() => NativeLibrary.TryLoad(AppKit, out _));
    private static nint Sel(string name) => sel_registerName(name);

    private readonly nint _pasteboard;

    /// <param name="name">Null for the general pasteboard (the real clipboard); a name for a private one, which tests use so
    /// they never touch what the owner copied.</param>
    public MacPasteboard(string? name = null)
    {
        if (!OperatingSystem.IsMacOS() || !Loaded.Value) throw new PlatformNotSupportedException("the macOS pasteboard needs macOS");
        var pool = objc_autoreleasePoolPush();
        try
        {
            var cls = objc_getClass("NSPasteboard");
            var pb = name is null ? Send(cls, Sel("generalPasteboard")) : Send(cls, Sel("pasteboardWithName:"), NSString(name));
            if (pb == 0) throw new InvalidOperationException("NSPasteboard is not available");
            _pasteboard = Send(pb, Sel("retain"));
        }
        finally { objc_autoreleasePoolPop(pool); }
    }

    public long ChangeCount
    {
        get
        {
            var pool = objc_autoreleasePoolPush();
            try { return SendLong(_pasteboard, Sel("changeCount")); }
            finally { objc_autoreleasePoolPop(pool); }
        }
    }

    public bool LastReadRefused { get; private set; }

    /// <summary>For tests: runs once the text has been read, before the types are checked again.</summary>
    internal Action? AfterTextRead;

    public string? ReadShareableText()
    {
        LastReadRefused = false;
        var pool = objc_autoreleasePoolPush();
        try
        {
            var (withheld, hasText) = Marks();
            if (withheld) return null;
            var item = Send(_pasteboard, Sel("stringForType:"), NSString(PlainText));
            AfterTextRead?.Invoke();
            // Again after the text: the change counter moves on clearContents, not on setString:forType:, so a password manager
            // that writes the text and then its concealed marker can add the marker after the first look without a new count.
            // The types promised text but none came. On macOS 15.4 and later that is how a read looks that the owner's paste
            // privacy setting denied (Apple documents nil for data that "cannot be obtained"); the bridge warns about it.
            if (item == 0) { LastReadRefused = hasText && !Marks().Withheld; return null; }
            // A copy far over the bridge's limit (a whole log file) is not converted: the bridge would drop it anyway, after the UTF-8
            // and managed copies (hundreds of MB) had been made while it holds its lock. Its UTF-16 length alone is enough to tell,
            // since UTF-8 never takes fewer bytes than the text has UTF-16 units.
            if (SendLong(item, Sel("length")) > ClipboardBridge.MaxBytes) return null;
            var text = Managed(item);
            return string.IsNullOrEmpty(text) || Marks().Withheld ? null : text;
        }
        finally { objc_autoreleasePoolPop(pool); }
    }

    /// <summary>Whether the current item carries a withheld marker, and whether it offers plain text at all (types only, no data).</summary>
    public bool CanShare(long changeCount)
    {
        var pool = objc_autoreleasePoolPush();
        try { return !Marks().Withheld && SendLong(_pasteboard, Sel("changeCount")) == changeCount; }
        finally { objc_autoreleasePoolPop(pool); }
    }

    private (bool Withheld, bool HasText) Marks()
    {
        var types = Send(_pasteboard, Sel("types"));
        if (types == 0) return (false, false);
        var hasText = false;
        var count = SendLong(types, Sel("count"));
        for (long i = 0; i < count; i++)
        {
            if (Managed(SendAt(types, Sel("objectAtIndex:"), (nuint)i)) is not { } type) continue;
            if (Array.IndexOf(Withheld, type) >= 0) return (true, hasText);
            hasText |= type == PlainText;
        }
        return (false, hasText);
    }

    /// <summary>
    /// macOS 15.4 added a paste privacy setting per app (NSPasteboardAccessBehavior: 0 default, 1 ask, 2 always allow, 3 always
    /// deny; AppKit's NSPasteboard.h). Reading the setting is not a read of the pasteboard. Older macOS has no such setting.
    /// </summary>
    public bool AccessDenied
    {
        get
        {
            var pool = objc_autoreleasePoolPush();
            try
            {
                var sel = Sel("accessBehavior");
                return SendBool(_pasteboard, Sel("respondsToSelector:"), sel) && SendLong(_pasteboard, sel) == AlwaysDeny;
            }
            finally { objc_autoreleasePoolPop(pool); }
        }
    }

    private const long AlwaysDeny = 3; // NSPasteboardAccessBehaviorAlwaysDeny

    public long? WriteText(string text)
    {
        var pool = objc_autoreleasePoolPush();
        try
        {
            // clearContents empties the clipboard before the text is set: if setString:forType: then fails (the caller answers
            // the phone 500), the Mac is left with an empty clipboard rather than what it held before. There is no way around
            // it: every way to put a new item on the pasteboard (clearContents, declareTypes:, prepareForNewContents) first empties it.
            var count = SendLong(_pasteboard, Sel("clearContents"));
            return SendBool(_pasteboard, Sel("setString:forType:"), NSString(text), NSString(PlainText)) ? count : null;
        }
        catch (InvalidOperationException) { return null; }
        finally { objc_autoreleasePoolPop(pool); }
    }

    /// <summary>For tests: adds another type to the current item, the way a password manager marks what it copies.</summary>
    internal void DeclareExtraType(string uti)
    {
        var pool = objc_autoreleasePoolPush();
        try { SendBool(_pasteboard, Sel("setString:forType:"), NSString(""), NSString(uti)); }
        finally { objc_autoreleasePoolPop(pool); }
    }

    /// <summary>For tests: removes a named pasteboard from the pasteboard server, which otherwise keeps it until logout.</summary>
    internal void ReleaseGlobally()
    {
        var pool = objc_autoreleasePoolPush();
        try { Send(_pasteboard, Sel("releaseGlobally")); }
        finally { objc_autoreleasePoolPop(pool); }
    }

    private const nuint Utf8 = 4; // NSUTF8StringEncoding

    /// <summary>
    /// An autoreleased NSString; valid until the surrounding pool is popped. Made from the bytes and their length, not from a C
    /// string: a text with a NUL in it ("A\0B") would otherwise be cut at the NUL while the caller believes it was written whole.
    /// </summary>
    private static nint NSString(string value)
    {
        var bytes = System.Text.Encoding.UTF8.GetBytes(value);
        var buffer = Marshal.AllocCoTaskMem(Math.Max(1, bytes.Length));
        try
        {
            Marshal.Copy(bytes, 0, buffer, bytes.Length);
            var made = SendBytes(Send(objc_getClass("NSString"), Sel("alloc")), Sel("initWithBytes:length:encoding:"), buffer, (nuint)bytes.Length, Utf8);
            return made == 0 ? 0 : Send(made, Sel("autorelease"));
        }
        finally { Marshal.FreeCoTaskMem(buffer); }
    }

    /// <summary>The text of an NSString by its UTF-8 length, so an embedded NUL does not end it early.</summary>
    private static string? Managed(nint nsString)
    {
        if (nsString == 0) return null;
        var length = SendLength(nsString, Sel("lengthOfBytesUsingEncoding:"), Utf8);
        return Send(nsString, Sel("UTF8String")) is var chars and not 0 ? Marshal.PtrToStringUTF8(chars, (int)length) : null;
    }
}
