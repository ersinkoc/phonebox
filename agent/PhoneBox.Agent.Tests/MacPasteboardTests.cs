using PhoneBox.Agent;
using Xunit;

/// <summary>
/// The macOS pasteboard behind the clipboard bridge. Every test uses a uniquely named private pasteboard, so the
/// owner's real clipboard is never read or changed by a test run. They do nothing off macOS.
/// </summary>
public sealed class MacPasteboardTests : IDisposable
{
    // named pasteboards live in the pasteboard server until logout unless released, so each test run would leave its own behind
    private readonly List<MacPasteboard> _made = [];

    private MacPasteboard? Fresh()
    {
        if (!OperatingSystem.IsMacOS()) return null;
        var pb = new MacPasteboard("phonebox-test-" + Guid.NewGuid().ToString("N"));
        _made.Add(pb);
        return pb;
    }

    public void Dispose()
    {
        foreach (var pb in _made) pb.ReleaseGlobally();
    }

    [Fact]
    public void NativeExceptionsAreConvertedBeforeReturningToManagedCode()
    {
        if (!OperatingSystem.IsMacOS()) return;
        Assert.Throws<InvalidOperationException>(MacPasteboard.ReadOutsideNativeArrayForTest);
    }

    [Fact]
    public void ATextAtTheBridgeLimitIsReadAndOneFarOverItIsNotConverted()
    {
        if (Fresh() is not { } pb) return;
        var atLimit = new string('a', ClipboardBridge.MaxBytes);
        Assert.NotNull(pb.WriteText(atLimit));
        Assert.Equal(atLimit, pb.ReadShareableText());
        Assert.NotNull(pb.WriteText(new string('a', ClipboardBridge.MaxBytes + 1)));
        Assert.Null(pb.ReadShareableText());   // a huge copy is dropped before it is turned into a managed string
    }

    [Fact]
    public void WriteThenReadRoundTripsUnicodeText()
    {
        if (Fresh() is not { } pb) return;
        Assert.NotNull(pb.WriteText("Καλημέρα 🌍\nsecond line"));
        Assert.Equal("Καλημέρα 🌍\nsecond line", pb.ReadShareableText());
    }

    [Fact]
    public void ATextWithANulIsWrittenAndReadBackWhole()
    {
        if (Fresh() is not { } pb) return;
        Assert.NotNull(pb.WriteText("left\0right"));
        Assert.Equal("left\0right", pb.ReadShareableText());     // not cut at the NUL, which "stringWithUTF8String:" would do
    }

    [Fact]
    public void ChangeCountIncreasesAfterAWrite()
    {
        if (Fresh() is not { } pb) return;
        var before = pb.ChangeCount;
        Assert.NotNull(pb.WriteText("one"));
        Assert.True(pb.ChangeCount > before);
    }

    [Fact]
    public void ReadingDoesNotChangeTheChangeCount()
    {
        if (Fresh() is not { } pb) return;
        pb.WriteText("steady");
        var count = pb.ChangeCount;
        for (var i = 0; i < 5; i++) pb.ReadShareableText();
        Assert.Equal(count, pb.ChangeCount);
    }

    [Theory]
    [InlineData("org.nspasteboard.ConcealedType")]
    [InlineData("org.nspasteboard.TransientType")]
    [InlineData("org.nspasteboard.AutoGeneratedType")]
    [InlineData("com.agilebits.onepassword")]
    [InlineData("de.petermaurer.TransientPasteboardType")]
    [InlineData("com.typeit4me.clipping")]
    [InlineData("Pasteboard generator type")]
    public void ItemsMarkedConcealedTransientOrAutoGeneratedReadAsNull(string marker)
    {
        if (Fresh() is not { } pb) return;
        pb.WriteText("hunter2");
        Assert.Equal("hunter2", pb.ReadShareableText());
        pb.DeclareExtraType(marker);
        Assert.Null(pb.ReadShareableText());
        Assert.False(pb.LastReadRefused);   // withheld on purpose, not refused by macOS
    }

    [Fact]
    public void AMarkerAddedWhileTheTextIsReadIsCaughtByTheSecondLookAtTheTypes()
    {
        // a password manager's setString("", concealed type) right after its setString(password): no new change count
        if (Fresh() is not { } pb) return;
        pb.WriteText("hunter2");
        var count = pb.ChangeCount;
        pb.AfterTextRead = () => pb.DeclareExtraType("org.nspasteboard.ConcealedType");
        Assert.Null(pb.ReadShareableText());
        Assert.Equal(count, pb.ChangeCount); // the marker really came without a new count
    }

    [Fact]
    public void ANamedPasteboardIsNeverDeniedAndAPlainReadIsNotARefusal()
    {
        if (Fresh() is not { } pb) return;
        Assert.False(pb.AccessDenied);       // macOS's paste privacy applies to the general pasteboard only
        pb.WriteText("fine");
        Assert.Equal("fine", pb.ReadShareableText());
        Assert.False(pb.LastReadRefused);
        pb.WriteText("");
        Assert.Null(pb.ReadShareableText());
        Assert.False(pb.LastReadRefused);    // an empty text came back as one, not as nothing
    }

    [Fact]
    public void AnEmptyPasteboardReadsAsNull()
    {
        if (Fresh() is not { } pb) return;
        Assert.Null(pb.ReadShareableText());
    }

    [Fact]
    public void ANamedPasteboardNeverTouchesTheGeneralOne()
    {
        // Only the general pasteboard's change count is read, never its contents. The developer may copy something while
        // the tests run, which moves that count too: then the check runs once more, and a write of ours that touched the
        // general pasteboard would move it again.
        if (!OperatingSystem.IsMacOS()) return;
        var general = new MacPasteboard();
        for (var attempt = 0; ; attempt++)
        {
            var before = general.ChangeCount;
            var named = Fresh()!;
            named.WriteText("not on the real clipboard");
            if (general.ChangeCount == before) return;
            if (attempt == 1) Assert.Equal(before, general.ChangeCount);
        }
    }
}
